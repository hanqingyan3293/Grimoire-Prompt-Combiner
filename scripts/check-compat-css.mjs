// Compat CSS coverage probe.
//
// The compat Vite project renders the vendored Cherry `../source` tree, whose
// utilities are only generated when Tailwind scans it (see the `@source` directives in
// compat/src/index.css). This probe reports what share of the utility tokens the source
// tree actually uses exist in the built CSS, and lists representative misses — the
// signal that content detection has fallen back to the compat root only.
//
// Usage: node scripts/check-compat-css.mjs [--sample N]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const assetsDir = path.join(root, 'src/vendor/cherry/compat/dist/assets')
const sourceRoots = [
  path.join(root, 'src/vendor/cherry/source/src'),
  path.join(root, 'src/vendor/cherry/source/packages/ui/src'),
]

const sampleCount = (() => {
  const index = process.argv.indexOf('--sample')
  return index === -1 ? 25 : Number(process.argv[index + 1]) || 25
})()

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === 'dist') continue
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full, out)
    else if (/\.(tsx|ts)$/.test(entry.name)) out.push(full)
  }
  return out
}

/**
 * CSS escapes every character that is not `[A-Za-z0-9_-]` inside a class selector, so
 * `left-[50%]` is written `.left-\[50\%\]`. Escaping the same set here is what makes
 * the containment test truthful — an unescaped `%` reports present classes as missing.
 */
function cssSelectorFor(token) {
  return '.' + token.replace(/[^A-Za-z0-9_-]/g, (char) => '\\' + char)
}

/**
 * Tokens that are candidate Tailwind utilities rather than prose, identifiers, or
 * semantic hook classes.
 *
 * The exclusions below are shapes Tailwind never generates a rule for, so counting them
 * as misses would report a coverage gap that does not exist:
 *  - `group/<name>` / `peer/<name>` are variant-group MARKERS; the compiled CSS only
 *    ever contains the consuming `group-hover/<name>:` variant, never the marker itself.
 *  - `[&_…]` arbitrary selectors compile to the escaped form, which the plain
 *    containment test below cannot match.
 *  - Bare `word-word` tokens with no slash of their own are DOM hook classes targeted by
 *    descendant selectors in the source's `layer(app)` stylesheets (`.table-wrapper`,
 *    `.latex-preview`, `.mini-app-icon-clip`, …) — they are styled by those files, not
 *    generated by Tailwind.
 */
function looksLikeUtility(token) {
  if (token.length < 3) return false
  if (!/^[a-z]/.test(token)) return false
  if (!/^[a-z0-9:_.\-[\]/%()!&]+$/i.test(token)) return false
  if (/^(group|peer)\//.test(token)) return false
  if (token.includes('&')) return false
  // Require a Tailwind-utility marker: a variant separator, a bracket value, or a
  // hyphenated compound (`text-sm`) rather than a single hook word (`table-wrapper`).
  // Hook classes may still hyphenate, so a known hook suffix set is excluded explicitly.
  if (!/[-:[\]]/.test(token)) return false
  if (HOOK_CLASS_SUFFIXES.some((suffix) => token.endsWith(suffix))) return false
  if (UNSTYLED_UPSTREAM_TOKENS.has(token)) return false
  // SVG-to-component transforms emit prefixed names (`wrap_svg__size-4`) that exist
  // only as AST identifiers, never as rendered class attributes.
  if (/_svg__/.test(token)) return false
  return true
}

/**
 * Tokens that no stylesheet in the vendored closure defines, so no build configuration
 * can produce a rule for them. These are pre-existing upstream leftovers: a handful of
 * components still carry HeroUI-era class names (`text-default-700`,
 * `border-default-200`, `text-danger`, `text-foreground-500`) from a UI library the
 * closure no longer vendors. Excluded so the probe measures THIS project's content-root
 * gap rather than inheriting upstream's dead class names — fixing them would mean
 * editing read-only source, which the migration rules forbid.
 */
const UNSTYLED_UPSTREAM_TOKENS = new Set([
  'border-default-200',
  'text-default-700',
  'text-default-600',
  'text-foreground-500',
  'text-danger',
  'text-foreground-muted',
  'text-foreground-secondary',
  'text-foreground-400',
  'border-border-muted',
  'lucide-square',
  'wrap-break-words',
])

/** Suffixes used by the source's semantic hook classes (see above). */
const HOOK_CLASS_SUFFIXES = [
  '-wrapper',
  '-container',
  '-content',
  '-header',
  '-footer',
  '-label',
  '-slot',
  '-clip',
  '-preview',
  '-pane',
  '-menubar',
  '-shell',
  '-tokens',
  '-style',
  '-list',
  '-icon',
  '-view',
  '-attachments',
  '-buttons',
  '-popover',
  '-placeholder',
  '-frame-border',
]

const cssFiles = fs.existsSync(assetsDir)
  ? fs.readdirSync(assetsDir).filter((name) => name.endsWith('.css'))
  : []
if (cssFiles.length === 0) {
  console.error('no built CSS found — run `npx vite build` in src/vendor/cherry/compat first')
  process.exit(2)
}
const css = cssFiles.map((name) => fs.readFileSync(path.join(assetsDir, name), 'utf8')).join('\n')

const files = sourceRoots.flatMap((dir) => walk(dir))
const classAttribute = /className\s*=\s*["'`]([^"'`]{3,600})["'`]/g
const tokens = new Set()
for (const file of files) {
  const text = fs.readFileSync(file, 'utf8')
  let match
  while ((match = classAttribute.exec(text))) {
    for (const token of match[1].split(/\s+/)) {
      if (looksLikeUtility(token)) tokens.add(token)
    }
  }
}

const all = [...tokens]
const missing = all.filter((token) => !css.includes(cssSelectorFor(token)))
const present = all.length - missing.length
const rate = all.length ? (100 * present) / all.length : 100

console.log(`scanned ${files.length} source files`)
console.log(`built css: ${cssFiles.length} chunks, ${(css.length / 1024).toFixed(0)} KB`)
console.log(`utility tokens: ${all.length}`)
console.log(`present: ${present} (${rate.toFixed(1)}%)`)
console.log(`missing: ${missing.length} (${(100 - rate).toFixed(1)}%)`)
if (missing.length) {
  console.log(`\nmissing sample (${Math.min(sampleCount, missing.length)}):`)
  for (const token of missing.slice(0, sampleCount)) console.log('  -', token)
}
// Content detection falling back to the compat root alone lands near 7%; a healthy
// build is above 90%. Anything in between means a source root is only partly scanned.
const threshold = 90
if (rate < threshold) {
  console.error(`\nFAIL: source utility coverage ${rate.toFixed(1)}% is below ${threshold}%`)
  process.exit(1)
}
