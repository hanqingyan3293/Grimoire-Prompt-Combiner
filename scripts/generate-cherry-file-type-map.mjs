// Generates `src/main/services/cherry-file-type-map.generated.ts` from the vendored Cherry
// source, and verifies the committed copy is current when run with `--check`.
//
//   node scripts/generate-cherry-file-type-map.mjs          # write
//   node scripts/generate-cherry-file-type-map.mjs --check  # verify (non-zero exit if stale)
//
// WHY GENERATE INSTEAD OF HAND-WRITING: the Files page renders its 类型 column from the source's
// `getFileTypeByExt`, and the backend `fileType` filter must agree with it or a row is listed
// under one type and then vanishes when that type is selected. The source's map is
// `imageExts|videoExts|audioExts|documentExts` plus `textExts`, and `textExts` is built from the
// linguist database — 1,377 extensions across codeLanguages.ts's 3,678 lines. Mirroring that by
// hand is a guaranteed drift, and an approximation (main's `file-bridge.service` table lists
// ~30 text extensions) silently mis-classifies hundreds of code files.
//
// The source files are NOT modified. This reads them and emits a derived data module.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'

const root = process.cwd()
const SOURCE_FILE_EXTENSIONS = path.join(root, 'src/vendor/cherry/source/src/shared/utils/file/fileExtensions.ts')
const SOURCE_CODE_LANGUAGES = path.join(root, 'src/vendor/cherry/source/src/shared/utils/codeLanguages.ts')
const OUTPUT = path.join(root, 'src/main/services/cherry-file-type-map.generated.ts')

const fileExtensionsText = fs.readFileSync(SOURCE_FILE_EXTENSIONS, 'utf8')
const codeLanguagesText = fs.readFileSync(SOURCE_CODE_LANGUAGES, 'utf8')

/** Reads an `export const <name> = [ '...', '...' ]` array literal by name. */
function readArrayLiteral(text, name) {
  const start = text.indexOf('export const ' + name)
  if (start === -1) return null
  const open = text.indexOf('[', start)
  const close = text.indexOf(']', open)
  if (open === -1 || close === -1) return null
  return [...text.slice(open, close).matchAll(/'(\.[^']+)'/g)].map(match => match[1].toLowerCase())
}

/** Reads the `customTextExts` Map's flat extension strings. */
function readCustomTextExts(text) {
  const start = text.indexOf('export const customTextExts')
  const end = text.indexOf('export const textExts', start)
  if (start === -1) return []
  return [...text.slice(start, end === -1 ? undefined : end).matchAll(/'(\.[^']+)'/g)].map(match => match[1].toLowerCase())
}

/** Every extension listed anywhere in the linguist data (`codeLanguages`). */
function readLinguistExts(text) {
  const start = text.indexOf('export const codeLanguages')
  const body = start === -1 ? text : text.slice(start)
  return [...body.matchAll(/'(\.?[A-Za-z0-9_+-]+)'/g)]
    .map(match => match[1])
    .filter(value => value.startsWith('.'))
    .map(value => value.toLowerCase())
}

const image = readArrayLiteral(fileExtensionsText, 'imageExts')
const video = readArrayLiteral(fileExtensionsText, 'videoExts')
const audio = readArrayLiteral(fileExtensionsText, 'audioExts')
const document = readArrayLiteral(fileExtensionsText, 'documentExts')

if (!image || !video || !audio || !document) {
  console.error('generate-cherry-file-type-map: could not read the source extension groups; refusing to emit a partial map')
  process.exit(1)
}

// Mirrors the source's `buildFileTypeMap`: `add(group, type)` in this exact order, so a later
// group wins nothing a `Map` would keep twice. `textExts` is customTextExts + linguist, deduped.
const text = [...new Set([...readCustomTextExts(fileExtensionsText), ...readLinguistExts(codeLanguagesText)])]
  .filter(ext => !image.includes(ext) && !video.includes(ext) && !audio.includes(ext) && !document.includes(ext))

if (text.length < 100) {
  // The linguist parse returning a handful of entries would mean the shape changed. Emitting a
  // tiny map would then look plausible while silently mis-classifying code files.
  console.error(`generate-cherry-file-type-map: parsed only ${text.length} text extensions; the source shape looks wrong, refusing to emit`)
  process.exit(1)
}

const digest = crypto.createHash('sha256')
  .update(fileExtensionsText + '\u0000' + codeLanguagesText)
  .digest('hex')
  .slice(0, 16)

const format = list => {
  const lines = []
  let current = '  '
  for (const item of list) {
    const token = `'${item}', `
    if (current.length + token.length > 118) { lines.push(current.trimEnd()); current = '  ' }
    current += token
  }
  if (current.trim()) lines.push(current.trimEnd())
  return lines.join('\n')
}

const output = `// AUTO-GENERATED by scripts/generate-cherry-file-type-map.mjs — DO NOT EDIT BY HAND.
// Source digest: ${digest}
//
// The ext → type grouping the source's \`fileTypeMap\` produces, derived from
// \`src/vendor/cherry/source/src/shared/utils/file/fileExtensions.ts\` and
// \`.../utils/codeLanguages.ts\`. Regenerate with \`npm run generate:cherry-file-type-map\`;
// \`npm run check:cherry-file-type-map\` fails when this file is out of date.
//
// Used by the Files page's \`fileType\` filter so the sidebar's 类型 filter agrees with the
// 类型 column the page renders from the SAME source table. An approximation here would list a
// row under one type and then hide it when that type is selected.

export type CherryFileType = 'image' | 'video' | 'audio' | 'text' | 'document' | 'other'

const IMAGE = new Set([
${format(image)}
])

const VIDEO = new Set([
${format(video)}
])

const AUDIO = new Set([
${format(audio)}
])

const DOCUMENT = new Set([
${format(document)}
])

const TEXT = new Set([
${format(text)}
])

/**
 * The source \`getFileTypeByExt\` contract: a leading dot is optional, matching is
 * case-insensitive, and anything unknown — including "no extension" — is \`'other'\`.
 *
 * \`'other'\` is NOT "unclassified": the source's own filter reads it as
 * \`ext IS NULL OR ext NOT IN (every known extension)\`, so the sets above must be exhaustive
 * for \`other\` to mean the same thing here.
 */
export function cherryFileTypeForExtension(ext: string | null | undefined): CherryFileType {
  const normalized = String(ext ?? '').replace(/^\\./, '').toLowerCase()
  if (!normalized) return 'other'
  const dotted = '.' + normalized
  if (IMAGE.has(dotted)) return 'image'
  if (VIDEO.has(dotted)) return 'video'
  if (AUDIO.has(dotted)) return 'audio'
  if (DOCUMENT.has(dotted)) return 'document'
  if (TEXT.has(dotted)) return 'text'
  return 'other'
}
`

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : ''
  if (current !== output) {
    console.error('check-cherry-file-type-map: cherry-file-type-map.generated.ts is OUT OF DATE.')
    console.error('Run `npm run generate:cherry-file-type-map` and review the diff.')
    process.exit(1)
  }
  console.log(`check-cherry-file-type-map: up to date (source digest ${digest}); image=${image.length} video=${video.length} audio=${audio.length} document=${document.length} text=${text.length}`)
  process.exit(0)
}

fs.writeFileSync(OUTPUT, output)
console.log(`wrote ${path.relative(root, OUTPUT)} (digest ${digest})`)
console.log(`image=${image.length} video=${video.length} audio=${audio.length} document=${document.length} text=${text.length}`)
