import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { DatabaseSync } from 'node:sqlite'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
let root = ''
vi.mock('electron', () => ({ app: { getPath: (name: string) => name === 'exe' ? path.join(root, 'Grimoire.exe') : root } }))
import { closeDatabase, CURRENT_SCHEMA_VERSION, getDatabase, initDatabase } from '../database'
import { appendTopicMessage, getTopicTreeState, initializeTopicTree, readTopicBranch, selectTopicContentNode } from './topic-tree.service'
import type { AppendTopicMessage } from '../../shared/topic-tree'
const now = '2026-01-01T00:00:00.000Z'
const dto = (text: string): AppendTopicMessage => ({ role: 'user', data: { parts: [{ type: 'text', text }] }, status: 'success' })
const raw = (sql: string) => getDatabase().exec(sql)
const legacyTables = ['ai_sessions', 'ai_messages', 'ai_events', 'ai_attachments', 'ai_topics', 'cherry_resource_state']
function legacySnapshot() { return legacyTables.map(table => raw(`SELECT * FROM ${table}`)) }
function treeSnapshot() { return [raw('SELECT * FROM topic_tree_state')[0]?.values ?? [], raw('SELECT * FROM topic_tree_messages')[0]?.values ?? []] }
function seed() {
  const db = getDatabase()
  db.run('INSERT INTO ai_sessions (id,kind,runtime,provider_id,model_id,title,status,metadata_json,created_at,updated_at) VALUES (?,?,?,?,?,?,?,?,?,?)', ['session', 'chat', 'openai-compatible', 'p', 'm', 'legacy', 'idle', '{"keep":1}', now, now])
  db.run('INSERT INTO ai_messages (id,session_id,sequence,role,content_json,attachments_json,status,created_at) VALUES (?,?,?,?,?,?,?,?)', ['legacy_msg', 'session', 7, 'assistant', '{"text":"NEVER ADOPT","nested":{"keep":true}}', '[{"id":"a"}]', 'completed', now])
  db.run('INSERT INTO ai_events (id,session_id,sequence,event_type,payload_json,created_at) VALUES (?,?,?,?,?,?)', ['event', 'session', 4, 'status', '{"keep":true}', now])
  db.run('INSERT INTO ai_attachments (id,session_id,message_id,file_path,created_at,updated_at) VALUES (?,?,?,?,?,?)', ['attachment', 'session', 'legacy_msg', 'C:/keep', now, now])
  for (const id of ['topic-a', 'topic-b']) db.run('INSERT INTO ai_topics (id,session_id,title,metadata_json,created_at,updated_at) VALUES (?,?,?,?,?,?)', [id, 'session', id, '{"keep":true}', now, now])
}
beforeEach(async () => { root = fs.mkdtempSync(path.join(os.tmpdir(), 'grimoire-topic-tree-')); await initDatabase(); seed() })
afterEach(() => { closeDatabase(); fs.rmSync(root, { recursive: true, force: true }) })
describe('P1 real SQLite opt-in topic tree adapter', () => {
  it('upgrades v32 with backup, no inferred trees, unchanged old tables/JSON/sequence, idempotent reopen', async () => {
    closeDatabase()
    const file = path.join(root, 'grimoire.db'), fixture = new DatabaseSync(file)
    fixture.exec('DROP TABLE topic_tree_state; DROP TABLE topic_tree_messages;')
    fixture.prepare("DELETE FROM schema_meta WHERE key='topic_trees_migrated'").run()
    fixture.prepare("UPDATE schema_meta SET value='32' WHERE key='schema_version'").run()
    fixture.close()
    await initDatabase()
    const before = legacySnapshot()
    expect(raw('SELECT * FROM topic_tree_state')[0].values).toEqual([])
    expect(raw('SELECT * FROM topic_tree_messages')[0].values).toEqual([])
    expect(raw("SELECT value FROM schema_meta WHERE key='schema_version'")[0].values[0][0]).toBe(String(CURRENT_SCHEMA_VERSION))
    const backups = fs.readdirSync(root).filter(n => n.includes('.pre-migration-') && n.endsWith('.bak'))
    expect(backups).toHaveLength(1)
    const backup = new DatabaseSync(path.join(root, backups[0]), { readOnly: true })
    expect(backup.prepare("SELECT value FROM schema_meta WHERE key='schema_version'").get()?.value).toBe('32')
    expect(backup.prepare("SELECT name FROM sqlite_master WHERE name='topic_tree_messages'").get()).toBeUndefined()
    // Compare upgraded rows against the actual pre-migration SQLite backup, not a post-upgrade baseline.
    for (let i = 0; i < legacyTables.length; i++) {
      const old = backup.prepare(`SELECT * FROM ${legacyTables[i]}`).all().map(row => Object.values(row))
      expect(before[i][0]?.values ?? []).toEqual(old)
    }
    backup.close()
    const state = initializeTopicTree('topic-a'), msg = appendTopicMessage('topic-a', dto('new'))
    const marker = raw("SELECT value FROM schema_meta WHERE key='topic_trees_migrated'")
    closeDatabase(); await initDatabase()
    expect(initializeTopicTree('topic-a')).toMatchObject({ ...state, activeNodeId: msg.id })
    expect(readTopicBranch('topic-a').items[0].message).toEqual(msg)
    expect(raw("SELECT value FROM schema_meta WHERE key='topic_trees_migrated'")).toEqual(marker)
    expect(legacySnapshot()).toEqual(before)
    expect(fs.readdirSync(root).filter(n => n.includes('.pre-migration-') && n.endsWith('.bak'))).toEqual(backups)
  })
  it('explicit unsupported legacy topic, real topic required, no implicit initialization', () => {
    expect(() => readTopicBranch('topic-a')).toThrow('UNSUPPORTED')
    expect(() => appendTopicMessage('topic-a', dto('no'))).toThrow('UNSUPPORTED')
    expect(() => selectTopicContentNode('topic-a', 'bad')).toThrow('UNSUPPORTED')
    expect(() => initializeTopicTree('missing')).toThrow('NOT_FOUND')
    expect(treeSnapshot()).toEqual([[], []])
  })
  it('two topics on one session own distinct roots/content; initialization never copies legacy history', () => {
    const before = legacySnapshot(), a = initializeTopicTree('topic-a'), b = initializeTopicTree('topic-b')
    expect(a.rootId).not.toBe(b.rootId)
    expect(a).toMatchObject({ activeNodeId: null, assistantId: null })
    expect(readTopicBranch('topic-a')).toMatchObject({ items: [], rootId: a.rootId, activeNodeId: null })
    expect(initializeTopicTree('topic-a')).toEqual(a)
    const ma = appendTopicMessage('topic-a', dto('A')), mb = appendTopicMessage('topic-b', dto('B'))
    expect(ma.parentId).toBe(a.rootId); expect(mb.parentId).toBe(b.rootId)
    expect(readTopicBranch('topic-a').items.map(i => i.message.id)).toEqual([ma.id])
    expect(readTopicBranch('topic-b').items.map(i => i.message.id)).toEqual([mb.id])
    expect(ma.id).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/)
    expect(raw("SELECT topic_id,count(*) FROM topic_tree_messages WHERE role='root' GROUP BY topic_id")[0].values).toEqual([['topic-a', 1], ['topic-b', 1]])
    expect(legacySnapshot()).toEqual(before)
  })
  it('source pending default, all statuses, internal selection forks exact node without leaf descent', () => {
    initializeTopicTree('topic-a')
    const first = appendTopicMessage('topic-a', dto('first')), child = appendTopicMessage('topic-a', dto('child'))
    selectTopicContentNode('topic-a', first.id)
    expect(readTopicBranch('topic-a').items.map(i => i.message.id)).toEqual([first.id])
    const fork = appendTopicMessage('topic-a', { role: 'assistant', data: {} })
    expect(fork).toMatchObject({ parentId: first.id, status: 'pending' })
    expect(readTopicBranch('topic-a', { nodeId: child.id }).items.map(i => i.message.id)).toEqual([first.id, child.id])
    expect(getTopicTreeState('topic-a').activeNodeId).toBe(fork.id)
    for (const status of ['success', 'error', 'paused'] as const) expect(appendTopicMessage('topic-a', { ...dto(status), status, setAsActive: false }).status).toBe(status)
    expect(getTopicTreeState('topic-a').activeNodeId).toBe(fork.id)
  })
  it('null parent means root; explicit root allowed; nonactivating writes preserve null or content selection', () => {
    const root = initializeTopicTree('topic-a').rootId
    const hidden = appendTopicMessage('topic-a', { ...dto('hidden'), setAsActive: false })
    expect(hidden.parentId).toBe(root)
    expect(readTopicBranch('topic-a').items).toEqual([])
    const first = appendTopicMessage('topic-a', dto('first'))
    expect(appendTopicMessage('topic-a', { ...dto('null'), parentId: null, setAsActive: false }).parentId).toBe(root)
    expect(appendTopicMessage('topic-a', { ...dto('root'), parentId: root, setAsActive: false }).parentId).toBe(root)
    expect(getTopicTreeState('topic-a').activeNodeId).toBe(first.id)
  })
  it('cross-topic parent/root/active and root selection reject with unchanged transaction state', () => {
    const a = initializeTopicTree('topic-a'), b = initializeTopicTree('topic-b')
    const other = appendTopicMessage('topic-b', dto('B')), before = treeSnapshot()
    for (const parentId of [other.id, b.rootId]) expect(() => appendTopicMessage('topic-a', { ...dto('bad'), parentId })).toThrow('INVALID_OPERATION')
    expect(() => selectTopicContentNode('topic-a', other.id)).toThrow('INVALID_OPERATION')
    expect(() => selectTopicContentNode('topic-a', a.rootId)).toThrow('INVALID_OPERATION')
    expect(() => readTopicBranch('topic-a', { nodeId: other.id })).toThrow('INVALID_OPERATION')
    expect(() => readTopicBranch('topic-a', { nodeId: a.rootId })).toThrow('INVALID_OPERATION')
    expect(treeSnapshot()).toEqual(before)
    // DB backstops also refuse direct invalid writes.
    expect(() => getDatabase().run('UPDATE topic_tree_state SET active_node_id=? WHERE topic_id=?', [other.id, 'topic-a'])).toThrow()
    expect(() => getDatabase().run('UPDATE topic_tree_state SET active_node_id=? WHERE topic_id=?', [a.rootId, 'topic-a'])).toThrow()
    expect(() => getDatabase().run('INSERT INTO topic_tree_messages SELECT ?,topic_id,parent_id,role,data_json,status,created_at,updated_at FROM topic_tree_messages WHERE id=?', ['11111111-1111-4111-8111-111111111111', a.rootId])).toThrow()
    expect(treeSnapshot()).toEqual(before)
  })
  it('latest path pagination exclusive cursor, oldest boundary, off-path/root/foreign cursor rejected; query never selects', () => {
    const a = initializeTopicTree('topic-a'); initializeTopicTree('topic-b')
    const nodes = Array.from({ length: 5 }, (_, i) => appendTopicMessage('topic-a', dto(String(i))))
    const foreign = appendTopicMessage('topic-b', dto('foreign'))
    const offPath = appendTopicMessage('topic-a', { ...dto('off'), parentId: nodes[0].id, setAsActive: false })
    const first = readTopicBranch('topic-a', { limit: 2 })
    expect(first.items.map(i => i.message.id)).toEqual(nodes.slice(3).map(n => n.id))
    expect(first.nextCursor).toBe(nodes[3].id)
    const second = readTopicBranch('topic-a', { limit: 2, cursor: first.nextCursor })
    expect(second.items.map(i => i.message.id)).toEqual(nodes.slice(1, 3).map(n => n.id))
    expect(second.nextCursor).toBe(nodes[1].id)
    expect(readTopicBranch('topic-a', { cursor: second.nextCursor, limit: 2 })).toMatchObject({ items: [{ message: nodes[0] }], nextCursor: undefined })
    expect(readTopicBranch('topic-a', { cursor: nodes[0].id }).items).toEqual([])
    for (const cursor of [offPath.id, foreign.id, a.rootId]) expect(() => readTopicBranch('topic-a', { cursor })).toThrow('NOT_FOUND')
    expect(readTopicBranch('topic-a', { nodeId: nodes[1].id }).items.map(i => i.message.id)).toEqual(nodes.slice(0, 2).map(n => n.id))
    expect(getTopicTreeState('topic-a').activeNodeId).toBe(nodes[4].id)
  })
  it('post-insert active update failure rolls back content; failed initialization rolls back root; next write works', () => {
    const db = getDatabase()
    db.exec("CREATE TRIGGER fail_init BEFORE INSERT ON topic_tree_state BEGIN SELECT RAISE(ABORT,'injected init failure'); END")
    expect(() => initializeTopicTree('topic-a')).toThrow('injected init failure')
    expect(treeSnapshot()).toEqual([[], []])
    db.exec('DROP TRIGGER fail_init'); initializeTopicTree('topic-a')
    const before = treeSnapshot()
    db.exec("CREATE TRIGGER fail_select BEFORE UPDATE ON topic_tree_state BEGIN SELECT RAISE(ABORT,'injected active failure'); END")
    expect(() => appendTopicMessage('topic-a', dto('rollback'))).toThrow('injected active failure')
    expect(treeSnapshot()).toEqual(before)
    db.exec('DROP TRIGGER fail_select')
    expect(appendTopicMessage('topic-a', dto('works')).data.parts?.[0].text).toBe('works')
  })
  it('rejects files/tool blob refs, unsupported sibling fields, wrong status, malformed JSON and cursors before mutation', () => {
    initializeTopicTree('topic-a'); const before = treeSnapshot()
    for (const data of [{ parts: [{ type: 'file', url: 'file://x' }] }, { parts: [{ type: 'dynamic-tool', output: { $persistedToolOutput: { blobs: [] } } }] }, { future: { fileEntryId: 'x' } }, { attachments: [] }, { parts: 'wrong' }, { parts: [null] }, { future: Infinity }, { future: undefined }, { modelSelection: 'invalid' }, { turnOptions: {} }]) expect(() => appendTopicMessage('topic-a', { ...dto('bad'), data } as unknown as AppendTopicMessage)).toThrow()
    for (const patch of [{ role: 'root' }, { status: 'completed' }, { setAsActive: 'false' }, { parentId: '' }, { siblingsGroupId: 1 }, { modelId: 'p::m' }]) expect(() => appendTopicMessage('topic-a', { ...dto('bad'), ...patch } as AppendTopicMessage)).toThrow()
    for (const query of [{ limit: 0 }, { limit: -1 }, { limit: 1.5 }, { cursor: '' }, { nodeId: '' }, { includeSiblings: true }]) expect(() => readTopicBranch('topic-a', query)).toThrow()
    expect(treeSnapshot()).toEqual(before)
  })
  it('orders ancestry explicitly under reverse_unordered_selects and refuses corrupt cycles boundedly', () => {
    initializeTopicTree('topic-a')
    const nodes = Array.from({ length: 4 }, (_, i) => appendTopicMessage('topic-a', dto(String(i))))
    const db = getDatabase()
    db.exec('PRAGMA reverse_unordered_selects=ON')
    expect(readTopicBranch('topic-a').items.map(i => i.message.id)).toEqual(nodes.map(n => n.id))
    db.exec('PRAGMA reverse_unordered_selects=OFF')
    // Simulate imported corruption only after deliberately disabling the topology backstop.
    db.exec('DROP TRIGGER topic_tree_topology_immutable')
    db.run('UPDATE topic_tree_messages SET parent_id=? WHERE id=?', [nodes[3].id, nodes[0].id])
    expect(() => readTopicBranch('topic-a')).toThrow('INTEGRITY')
  })
  it('archive makes existing tree non-addressable without deleting it', () => {
    initializeTopicTree('topic-a'); appendTopicMessage('topic-a', dto('keep'))
    const before = treeSnapshot()
    getDatabase().run('UPDATE ai_topics SET archived=1 WHERE id=?', ['topic-a'])
    expect(() => readTopicBranch('topic-a')).toThrow('NOT_FOUND')
    expect(() => appendTopicMessage('topic-a', dto('bad'))).toThrow('NOT_FOUND')
    expect(treeSnapshot()).toEqual(before)
  })
})
